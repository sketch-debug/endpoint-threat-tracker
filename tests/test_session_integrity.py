"""Phase-1 audit regressions: session purge, UTC timestamps, privilege
freshness, and the SECRET_KEY wiring.

Each test pins a defect found by a read-only audit:

1. purge_expired() read `.rowcount` off Database.execute()'s int return, so
   the scheduler's sessions job raised AttributeError on every run (the
   DELETE landed, but the job always errored - alarm noise that masks real
   failures, and the function was never covered).
2. create_session() stamped expiry with naive local datetime.now() while
   resolve_session compares against UTC now_iso(): on UTC-offset hosts the
   real TTL was off by the offset - short west of Greenwich, LONG (failing
   open) east of it.
3. incidents._plus_days() had the same local-vs-UTC skew, moving the 14-day
   re-check deadline by the host offset.
4. resolve_session() read role from the sessions row, so a demoted admin
   kept admin until the cookie expired; set_password() left live sessions
   alive, so resetting a compromised account did not evict the intruder.
5. SECRET_KEY (.env, generated by install.ps1, documented as signing
   session cookies) was never read by anything.
"""
from __future__ import annotations

import hashlib
from datetime import timedelta

import pytest
from fastapi.testclient import TestClient

from app import auth, incidents
from app.main import create_app
from app.normalize import iso, now_iso, utcnow


# ---- 1. purge_expired -----------------------------------------------------

def test_purge_expired_counts_deletes_without_raising(db, settings) -> None:
    """The bug: `cur.rowcount` on an int raised AttributeError every run."""
    auth.create_user(db, "alice", "alices-password", "analyst", actor="system")
    live = auth.create_session(db, settings, "alice", "analyst")
    with db.tx():
        db.execute(
            "INSERT INTO sessions(token_hash, username, role, created_at, "
            "expires_at) VALUES('expired-hash','ghost','viewer',?,?)",
            ("2020-01-01T00:00:00", "2020-01-02T00:00:00"))

    removed = auth.purge_expired(db)   # must not raise

    assert removed == 1
    assert db.one("SELECT COUNT(*) AS n FROM sessions")["n"] == 1
    # the live session is untouched and still resolves
    assert auth.resolve_session(db, settings, live) is not None
    # and running it again is a clean no-op
    assert auth.purge_expired(db) == 0


# ---- 2. session expiry in UTC --------------------------------------------

def test_session_expiry_is_utc_zulu_and_about_12h_out(db, settings) -> None:
    auth.create_user(db, "alice", "alices-password", "analyst", actor="system")
    cookie = auth.create_session(db, settings, "alice", "analyst")
    row = db.one("SELECT expires_at FROM sessions WHERE username='alice'")
    expires = row["expires_at"]

    assert expires.endswith("Z"), \
        f"must use the same Z-format now_iso() compares against, got {expires!r}"
    from datetime import datetime
    parsed = datetime.strptime(expires, "%Y-%m-%dT%H:%M:%SZ").replace(
        tzinfo=utcnow().tzinfo)
    delta = parsed - utcnow()
    assert timedelta(hours=11, minutes=59) <= delta <= timedelta(hours=12, minutes=1)

    # fresh session resolves; a past-Z expiry does not
    assert auth.resolve_session(db, settings, cookie) is not None


def test_past_zulu_expiry_does_not_resolve(db, settings) -> None:
    auth.create_user(db, "alice", "alices-password", "analyst", actor="system")
    token = "expired-token"
    sig = auth._sign(auth._session_secret(settings), token)
    with db.tx():
        db.execute(
            "INSERT INTO sessions(token_hash, username, role, created_at, "
            "expires_at) VALUES(?,?,?,?,?)",
            (hashlib.sha256(token.encode()).hexdigest(), "alice", "analyst",
             now_iso(), iso(utcnow() - timedelta(minutes=1))))
    assert auth.resolve_session(db, settings, f"{token}.{sig}") is None


def test_legacy_non_utc_expiry_rows_keep_working(db, settings) -> None:
    """Rows written by the old code (no Z suffix) must still order correctly
    against now_iso() in string comparison - only the date differs."""
    token = "legacy-token"
    sig = auth._sign(auth._session_secret(settings), token)
    token_hash = hashlib.sha256(token.encode()).hexdigest()
    auth.create_user(db, "alice", "alices-password", "analyst", actor="system")

    with db.tx():
        # future expiry, legacy naive format -> still valid
        db.execute(
            "INSERT INTO sessions(token_hash, username, role, created_at, "
            "expires_at) VALUES(?,?,?,?,?)",
            (token_hash, "alice", "analyst", now_iso(), "2099-01-01T00:00:00"))
    assert auth.resolve_session(db, settings, f"{token}.{sig}") is not None

    with db.tx():
        db.execute("UPDATE sessions SET expires_at='2020-01-01T00:00:00' "
                   "WHERE token_hash=?", (token_hash,))
    assert auth.resolve_session(db, settings, f"{token}.{sig}") is None


# ---- 3. recheck deadline in UTC ------------------------------------------

def test_plus_days_is_utc_within_a_minute() -> None:
    from datetime import datetime
    got = incidents._plus_days(14)
    assert got.endswith("Z"), f"recheck deadline must be UTC/Z, got {got!r}"
    parsed = datetime.strptime(got, "%Y-%m-%dT%H:%M:%SZ").replace(
        tzinfo=utcnow().tzinfo)
    expected = utcnow() + timedelta(days=14)
    assert abs((parsed - expected).total_seconds()) <= 60


def test_verified_transition_stores_zulu_recheck_deadline(db, settings) -> None:
    """Integration: transition_pc writes a Z-suffixed recheck_until."""
    from app import incidents as inc
    inc_id = _incident_with_pc(db, settings, "PC-Z")
    inc.transition_pc(db, settings, inc_id, "PC-Z", "isolated", "alice")
    inc.transition_pc(db, settings, inc_id, "PC-Z", "verified", "alice")
    row = db.one("SELECT recheck_until FROM incident_pcs WHERE incident_id=?",
                 (inc_id,))
    assert row and row["recheck_until"].endswith("Z")
    # and the sweep compares it correctly (deadline still in the future)
    from app import recheck as recheck_mod
    swept = recheck_mod.run_recheck_sweep(db, settings)
    assert swept["rechecks_passed"] == 0, "a fresh 14-day window must not pass"


def _incident_with_pc(db, settings, pc: str) -> int:
    """Seed one signal, correlate it into an incident, return its id."""
    import itertools
    seq = itertools.count(1)
    db.execute(
        "INSERT INTO signals(ts, pc, rule_id, category, weight, title, "
        "detail, correlation, dedup_key) VALUES(?,?,?,?,?,?,?,?,?)",
        (now_iso(), pc, "proc_miner_name", "miner", 25, "miner", "", "[]",
         f"{pc}|seed|{next(seq)}"))
    sig = dict(db.one("SELECT * FROM signals ORDER BY id DESC LIMIT 1"))
    inc, _ = incidents.correlate_and_record(db, settings, sig, "medium",
                                            ["miner"], ["proc_miner_name"])
    return int(inc["id"])


# ---- 4. privilege freshness ----------------------------------------------

def _app_client(settings):
    app = create_app(settings)
    return app, TestClient(app)


def test_demoted_admin_loses_admin_on_the_next_request(settings) -> None:
    app, client = _app_client(settings)
    db = app.state.db
    auth.create_user(db, "carol", "carols-password", "admin", actor="system")
    cookie = auth.create_session(db, settings, "carol", "admin")

    assert client.get("/config", cookies={auth.SESSION_COOKIE: cookie}).status_code == 200

    auth.set_role(db, "carol", "viewer", actor="system")

    # same cookie, no re-login: the role must come from users, not the session
    resp = client.get("/config", cookies={auth.SESSION_COOKIE: cookie})
    assert resp.status_code == 403, "demoted admin kept admin until cookie expiry"
    # read-only pages still work for the demoted user
    assert client.get("/", cookies={auth.SESSION_COOKIE: cookie}).status_code == 200


def test_password_change_revokes_existing_sessions(db, settings) -> None:
    """An admin resetting a compromised account must evict live cookies."""
    auth.create_user(db, "dave", "daves-old-password", "analyst", actor="system")
    cookie = auth.create_session(db, settings, "dave", "analyst")
    assert auth.resolve_session(db, settings, cookie) is not None

    auth.set_password(db, "dave", "brand-new-password", actor="admin")

    assert auth.resolve_session(db, settings, cookie) is None, \
        "the old session survived the password reset"
    # ...and the new password works (bootstrap/install sync path still holds)
    row = db.one("SELECT password_hash FROM users WHERE username='dave'")
    assert auth.verify_password("brand-new-password", row["password_hash"])


def test_deleted_users_session_dies_with_them(db, settings) -> None:
    auth.create_user(db, "erin", "erins-password", "viewer", actor="system")
    cookie = auth.create_session(db, settings, "erin", "viewer")
    assert auth.resolve_session(db, settings, cookie) is not None

    auth.delete_user(db, "erin", actor="system")

    # delete_user already removes session rows; the INNER JOIN is a second
    # line of defense for any row that slips through
    assert auth.resolve_session(db, settings, cookie) is None


# ---- 5. SECRET_KEY wiring -------------------------------------------------

def test_secret_key_env_signs_cookies(db, settings,
                                      monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.delenv("SESSION_SECRET", raising=False)
    monkeypatch.setenv("SECRET_KEY", "the-env-signing-key")
    auth.create_user(db, "frank", "franks-password", "analyst", actor="system")

    cookie = auth.create_session(db, settings, "frank", "analyst")
    assert auth.resolve_session(db, settings, cookie) is not None

    # rotating SECRET_KEY invalidates previously issued cookies
    monkeypatch.setenv("SECRET_KEY", "rotated-key")
    assert auth.resolve_session(db, settings, cookie) is None
    fresh = auth.create_session(db, settings, "frank", "analyst")
    assert auth.resolve_session(db, settings, fresh) is not None


def test_session_secret_env_still_wins_over_secret_key(
        db, settings, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("SESSION_SECRET", "explicit-override")
    monkeypatch.setenv("SECRET_KEY", "lesser-key")
    assert auth._session_secret(settings) == "explicit-override"
